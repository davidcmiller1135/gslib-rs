//! Every committed fixture must be complete and consistent (R6).

#[cfg(test)]
mod fixtures {
    use std::path::{Path, PathBuf};

    fn fixture_root() -> PathBuf {
        harness::fixture_root()
    }

    /// Fails on the first fixture with a missing file, an invalid schema or
    /// provenance record, or a `case.toml` edited since generation.
    #[test]
    fn all_committed_fixtures_are_valid() {
        let fixtures = oracle_case::discover(&fixture_root()).unwrap();
        // Fixtures from an older recipe are still valid evidence, but say so
        // (D-014): regenerating would show whether the recipe change matters.
        let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("..");
        let current = oracle_case::recipe_sha256(&root).unwrap();
        for f in fixtures
            .iter()
            .filter(|f| f.provenance.recipe_sha256 != current)
        {
            println!("note: {} was generated by an older recipe", f.dir.display());
        }
        // An input named like a synthetic suite must still match it.
        let data = fixture_root().join("../data");
        for f in &fixtures {
            for input in &f.case.inputs {
                if let Ok(suite) = std::fs::read(data.join(input)) {
                    let used = std::fs::read(f.dir.join(input)).unwrap();
                    assert!(
                        used == suite,
                        "{}: {input} differs from the data suite; regenerate the fixture",
                        f.dir.display()
                    );
                }
            }
        }
        for f in &fixtures {
            assert!(
                f.dir.starts_with(fixture_root()),
                "fixture outside the fixture root: {}",
                f.dir.display()
            );
        }
    }
}
